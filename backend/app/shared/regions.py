def is_region(sido: str, sgg: str) -> bool:
    return sgg in SGG.get(sido, set())


def region_label(sido: str, sgg: str) -> str:
    """화면에 보일 이름: 서울 마포구, 광주 광산구, 세종시"""
    for _, prefix, items in SIDO.get(sido, ("", "", []))[2]:
        if sgg in items:
            return f"{prefix} {sgg}" if prefix else sgg
    return sgg


def emd_list(sido: str, sgg: str) -> list[dict[str, str]]:
    """읍면동 목록 [{code, name}] (GET /regions/{sido}/{sgg}). 자료가 없는 구는 빈 목록이에요"""
    return [{"code": c, "name": n} for c, n in EMD.get((sido, sgg), ())]


def is_emd(sido: str, sgg: str, emd: str) -> bool:
    """읍면동 이름이 그 구의 법정동인지. 자료가 없는 구는 False예요(구 단위로만 받아요)"""
    return any(n == emd for _, n in EMD.get((sido, sgg), ()))


