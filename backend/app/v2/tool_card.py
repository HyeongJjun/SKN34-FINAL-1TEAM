"""도구 카드 고르기: 질문 낱말 → 화면 도구 카드(셀프 계산기 · 체크리스트 · 받은 견적 맞춰 보기 · 화면 단계 열기).

LLM 없이 코드 표로 고른다. 같은 질문이면 같은 카드가 나온다. 수량은 카드(화면 계산)가 내고
답 글은 카드로 안내만 한다. 위에서부터 먼저 맞는 카드 하나만 고른다.
"""

import re
from typing import Literal

from app.v2.schemas import V2AskCard

Tool = Literal["calc", "check", "compare", "step"]

# 수량을 묻는 말. '얼마나 들어'는 돈을 묻는 말이라 넣지 않는다
QTY = (
    r"(?:몇\s*(?:롤|개|통|말|m|미터|리터|L|장)|롤\s*수|수량|"
    r"얼마나\s*(?:필요|사야|사면|주문)|양(?:이|은|을)?\s*(?:얼마|몇|계산))"
)
CALC = (
    "직접 세거나 수량을 말하지 말고, 방 크기를 넣으면 이 계산기가 세 준다고 답 끝에 한 줄로 안내해."
)
CHECK = "답은 자료로 하고, 답 끝에 이 버튼으로 하나씩 확인해 보라고 한 줄로 안내해."
# 보여 달라는 말. '보여 주면' · '보여 줄게요'(고객이 보여 주겠다는 말) · '사진 찍어'는 아니다
SHOW_ME = r"(?:보여\s*(?:줘|줄\s*래|줄\s*수|주세|주실|주시|달)|구경)"
# '볼 수 · 보고 싶'은 볼 것(견적서 · 사진 · 견본)이 같이 있을 때만 쓴다. '해볼 수 · 알아볼 수'는 보는 말이 아니다
SEE = rf"(?:{SHOW_ME}|(?<![가-힣])볼\s*수|보고\s*싶)"
LOOK = r"(?:이미지|사진|견본|샘플|디자인|무늬|색)"
SHOW = "'보여 드릴 수 없어요'라고 하지 말고, 이 버튼을 누르면 화면에서 바로 볼 수 있다고 한 줄로 안내해."

# (도구, 화면 인자, 버튼 글, 낱말, 지시문 힌트). step의 화면 인자는 ask_tools.STEPS의 단계 이름
CARDS: tuple[tuple[Tool, str | None, str, re.Pattern[str], str], ...] = (
    (
        "calc", "trim", "셀프 계산기로 몰딩 · 걸레받이 세기",
        re.compile(rf"(?:몰딩|걸레받이|굽도리).{{0,12}}{QTY}|{QTY}.{{0,8}}(?:몰딩|걸레받이|굽도리)"),
        CALC,
    ),
    (
        "calc", "paint", "셀프 계산기로 페인트 양 세기",
        re.compile(rf"(?:페인트|도료).{{0,12}}{QTY}|{QTY}.{{0,8}}(?:페인트|도료)"),
        CALC,
    ),
    (
        "calc", "wall", "셀프 계산기로 벽지 롤 세기",
        re.compile(rf"벽지.{{0,12}}{QTY}|{QTY}.{{0,8}}벽지|몇\s*롤|롤\s*수"),
        CALC,
    ),
    (
        "check", "after", "체크리스트: 공사 뒤 검수",
        re.compile(
            r"검수|하자\s*(?:확인|점검|체크)|잔금\s*(?:전|내기\s*전|치기\s*전)|"
            r"공사\s*(?:끝나고|끝난\s*뒤|후에?)\s*(?:뭘|무엇을|확인|점검)"
        ),
        CHECK,
    ),
    (
        "check", "contract", "체크리스트: 계약 전 확인",
        re.compile(r"계약서|계약\s*(?:전|하기\s*전|할\s*때)|계약.{0,6}(?:확인|체크)할"),
        CHECK,
    ),
    (
        "check", "before", "체크리스트: 공사 전 준비",
        # 승강기 · 엘리베이터는 공사 준비(보양 · 사용 신청 · 사용료)를 물을 때만. '엘리베이터 없는 5층'은 아니다
        re.compile(
            r"관리\s*사무소|공사\s*(?:신고|동의|안내문)|동의서|"
            r"(?:승강기|엘리베이터).{0,6}(?:보양|사용|신청|예약|신고)"
        ),
        CHECK,
    ),
    (
        "compare", None, "받은 견적 맞춰 보기",
        re.compile(r"(?:받은|나온|받아\s*본)\s*견적|견적.{0,8}(?:받았|나왔|받아\s*봤)"),
        "답 끝에 받은 금액을 이 버튼에 넣으면 같은 평수 · 범위의 시장 기준과 견줘 볼 수 있다고 한 줄로 안내해.",
    ),
    (
        "step", "quote", "표준견적서 보기",
        re.compile(rf"견적서.{{0,6}}(?:양식|예시|샘플|{SEE})"),
        SHOW,
    ),
    (
        "step", "materials", "벽지 견본 보기",
        re.compile(
            rf"(?:벽지|도배지?|실크|합지).{{0,10}}{LOOK}.{{0,8}}{SEE}"
            rf"|(?:벽지|도배지?).{{0,6}}{SHOW_ME}"
        ),
        SHOW,
    ),
    (
        "step", "styles", "스타일 사진 보기",
        re.compile(
            rf"(?:스타일|인테리어|분위기|느낌).{{0,10}}(?:이미지|사진|예시|시안).{{0,8}}{SEE}"
            rf"|(?:스타일|분위기).{{0,6}}{SHOW_ME}"
        ),
        SHOW,
    ),
)  # fmt: skip


def pick(question: str) -> tuple[V2AskCard, str] | None:
    """(화면 카드, 지시문 힌트). 맞는 카드가 없으면 None"""
    for tool, arg, label, words, how in CARDS:
        if words.search(question):
            hint = f"화면 도구(코드가 고름): 답 아래에 '{label}' 버튼이 같이 보여. {how} '다음에 할 일:' 같은 머리말은 붙이지 마."
            return V2AskCard(tool=tool, arg=arg, label=label), hint
    return None
